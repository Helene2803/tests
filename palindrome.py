def palindrome(phrases: list) -> list:
    result = [] # список палиндромов
    for phrase in phrases: # пройдите циклом по всем фразам
        phr = ''
        for letter in phrase: # сохраните фразу без пробелов
            if letter == ' ':
                continue
            else:
                phr += letter
        if phr == phr[::-1]: # сравните фразу с ней же, развернутой наоборот
            result.append(phrase) # добавьте в список палиндромов отобранные фразы

    # print(result) # раскомментируйте эту строку, если хотите проверить  результат вашего кода
    return result

# список фраз, которые нужно проверить на палиндром
# вы можете добавлять в список свои фразы
phrases = [
    "нажал кабан на баклажан",
    "дом как комод",
    "рвал дед лавр",
    "азот калий и лактоза",
    "а собака боса",
    "тонет енот",
    "карман мрак",
    "пуст суп",
    "а роза упала на лапу азора"
]

result = palindrome(phrases)
